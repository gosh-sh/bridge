#[cfg(test)]
mod tests {
    use super::*;

    /// `squeeze_challenge` on an empty transcript must be deterministic — same
    /// state, same output across two independent constructions. Guards
    /// against accidental randomness in spec generation.
    #[test]
    fn empty_squeeze_is_deterministic() {
        let mut a = NativePoseidon::new();
        let mut b = NativePoseidon::new();
        assert_eq!(a.squeeze(), b.squeeze());
    }

    /// Two writers fed the same scalars must produce identical proof bytes
    /// AND identical squeezed challenges — i.e. the transcript state evolves
    /// deterministically from the inputs.
    #[test]
    fn write_then_read_round_trip_scalars() {
        let xs: Vec<Fr> = (0..7).map(|i| Fr::from(i as u64 + 1)).collect();

        let mut writer = PoseidonWrite::init(Vec::<u8>::new());
        for s in &xs {
            writer.write_scalar(*s).unwrap();
        }
        let challenge_w: Fr = writer.squeeze_challenge().get_scalar();
        let bytes = writer.finalize();

        // Each scalar serialises to 32 bytes.
        assert_eq!(bytes.len(), xs.len() * 32);

        let mut reader = PoseidonRead::init(bytes.as_slice());
        let mut read_back = Vec::with_capacity(xs.len());
        for _ in &xs {
            read_back.push(reader.read_scalar().unwrap());
        }
        let challenge_r: Fr = reader.squeeze_challenge().get_scalar();

        assert_eq!(read_back, xs);
        assert_eq!(challenge_w, challenge_r);
    }

    /// EC points absorb as the (x,y) base-field coordinates reduced to Fr.
    /// We verify a write/read round-trip recovers identical points and
    /// identical post-state challenges.
    #[test]
    fn write_then_read_round_trip_points() {
        use halo2_base::halo2_proofs::halo2curves::{
            bn256::G1,
            group::{Curve, Group},
        };
        use rand::SeedableRng;

        let mut rng = rand::rngs::StdRng::seed_from_u64(0xC0FFEE);
        let points: Vec<G1Affine> = (0..5)
            .map(|_| {
                let p = G1::random(&mut rng);
                p.to_affine()
            })
            .collect();

        let mut writer = PoseidonWrite::init(Vec::<u8>::new());
        for p in &points {
            writer.write_point(*p).unwrap();
        }
        let challenge_w: Fr = writer.squeeze_challenge().get_scalar();
        let bytes = writer.finalize();
        assert_eq!(bytes.len(), points.len() * 32); // compressed G1Affine = 32 B

        let mut reader = PoseidonRead::init(bytes.as_slice());
        let mut read_back = Vec::with_capacity(points.len());
        for _ in &points {
            read_back.push(reader.read_point().unwrap());
        }
        let challenge_r: Fr = reader.squeeze_challenge().get_scalar();

        assert_eq!(read_back, points);
        assert_eq!(challenge_w, challenge_r);
    }

    /// Tampered bytes flip the read scalars and therefore the squeezed
    /// challenges — a sanity check that the transcript is actually using
    /// the read data (not silently ignoring it).
    #[test]
    fn tampered_proof_changes_challenge() {
        let xs: Vec<Fr> = (0..3).map(|i| Fr::from(i as u64 + 1)).collect();

        let mut writer = PoseidonWrite::init(Vec::<u8>::new());
        for s in &xs {
            writer.write_scalar(*s).unwrap();
        }
        let challenge_clean: Fr = writer.squeeze_challenge().get_scalar();
        let mut bytes = writer.finalize();

        // Flip a single bit deep inside the second scalar (still a valid Fr
        // element — flipping low bit can never overflow the modulus).
        bytes[32] ^= 0x01;

        let mut reader = PoseidonRead::init(bytes.as_slice());
        for _ in &xs {
            let _ = reader.read_scalar().unwrap();
        }
        let challenge_tampered: Fr = reader.squeeze_challenge().get_scalar();

        assert_ne!(challenge_clean, challenge_tampered);
    }

    /// Construct the spec twice and check round-constant determinism. This
    /// guards against any future surprise where round-constant generation
    /// pulls entropy.
    #[test]
    fn spec_is_deterministic() {
        let a: OptimizedPoseidonSpec<Fr, POSEIDON_T, POSEIDON_RATE> =
            OptimizedPoseidonSpec::new::<POSEIDON_R_F, POSEIDON_R_P, POSEIDON_SECURE_MDS>();
        let b: OptimizedPoseidonSpec<Fr, POSEIDON_T, POSEIDON_RATE> =
            OptimizedPoseidonSpec::new::<POSEIDON_R_F, POSEIDON_R_P, POSEIDON_SECURE_MDS>();
        assert_eq!(a.constants().start(), b.constants().start());
        assert_eq!(a.constants().partial(), b.constants().partial());
        assert_eq!(a.constants().end(), b.constants().end());
    }
}
